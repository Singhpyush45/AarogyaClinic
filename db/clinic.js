async function updateVisitStatus(visitId, status, doctorId = null) {
  if (doctorId) {
    await pool.query(`UPDATE visits SET status = $1, doctor_id = $2 WHERE id = $3`, [status, doctorId, visitId]);
  } else {
    await pool.query(`UPDATE visits SET status = $1 WHERE id = $2`, [status, visitId]);
  }
  return getVisitWithPatient(visitId);
}

async function getBillingQueue() {
  const { rows } = await pool.query(
    `SELECT v.*, p.first_name, p.last_name, p.phone,
       su.username AS doctor_username, sp.full_name AS doctor_name
     FROM visits v
     JOIN patients p ON p.id = v.patient_id
     LEFT JOIN staff_users su ON su.id = v.doctor_id
     LEFT JOIN staff_profiles sp ON sp.staff_user_id = v.doctor_id
     WHERE v.status = 'ready_for_billing' ORDER BY v.created_at ASC`
  );
  return rows;
}

async function getDoctorStats(doctorId) {
  const today = new Date().toISOString().slice(0, 10);
  const queueQ = pool.query(`SELECT COUNT(*)::int AS c FROM visits WHERE status = 'waiting'`);
  const seenTodayQ = pool.query(
    `SELECT COUNT(*)::int AS c FROM visits WHERE doctor_id = $1 AND created_at::date = $2 AND status != 'waiting'`,
    [doctorId, today]
  );
  const totalSeenQ = pool.query(`SELECT COUNT(*)::int AS c FROM visits WHERE doctor_id = $1 AND status != 'waiting'`, [doctorId]);
  const [queue, seenToday, totalSeen] = await Promise.all([queueQ, seenTodayQ, totalSeenQ]);
  return { queueCount: queue.rows[0].c, seenToday: seenToday.rows[0].c, totalSeen: totalSeen.rows[0].c };
}

async function getBillingStats(staffId) {
  const today = new Date().toISOString().slice(0, 10);
  const pendingQ = pool.query(`SELECT COUNT(*)::int AS c FROM visits WHERE status = 'ready_for_billing'`);
  const billsTodayQ = pool.query(`SELECT COUNT(*)::int AS c FROM bills WHERE created_at::date = $1`, [today]);
  const revenueTodayQ = pool.query(`SELECT COALESCE(SUM(grand_total),0)::numeric(10,2) AS s FROM bills WHERE created_at::date = $1`, [today]);
  // total value of medicines billed today (per bill generation, not incl. consulting fee)
  const medicineRevenueTodayQ = pool.query(
    `SELECT COALESCE(SUM(bi.line_total),0)::numeric(10,2) AS s FROM bill_items bi
     JOIN bills b ON b.id = bi.bill_id WHERE b.created_at::date = $1`,
    [today]
  );
  const [pending, billsToday, revenueToday, medicineRevenueToday] = await Promise.all([pendingQ, billsTodayQ, revenueTodayQ, medicineRevenueTodayQ]);
  return {
    pendingCount: pending.rows[0].c,
    billsToday: billsToday.rows[0].c,
    revenueToday: revenueToday.rows[0].s,
    medicineRevenueToday: medicineRevenueToday.rows[0].s,
  };
}

