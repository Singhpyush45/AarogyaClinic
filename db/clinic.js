async function getPrescriptionByVisit(visitId) {
  const { rows } = await pool.query(
    `SELECT * FROM prescriptions WHERE visit_id = $1 ORDER BY created_at DESC LIMIT 1`,
    [visitId]
  );
  if (!rows[0]) return null;
  const prescription = rows[0];
  const { rows: meds } = await pool.query(
    `SELECT * FROM prescription_medicines WHERE prescription_id = $1`,
    [prescription.id]
  );
  prescription.medicines = meds;
  return prescription;
}

