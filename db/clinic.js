// ============================= DATE RANGE HELPER =============================
function resolveDateRange(range, fromParam, toParam) {
  const now = new Date();
  const startOfDay = (d) => new Date(d.getFullYear(), d.getMonth(), d.getDate());
  let from, to;
  to = startOfDay(now);
  to.setDate(to.getDate() + 1); // exclusive upper bound = tomorrow 00:00

  switch (range) {
    case 'today':
      from = startOfDay(now);
      break;
    case 'yesterday':
      from = startOfDay(now); from.setDate(from.getDate() - 1);
      to = startOfDay(now);
      break;
    case 'this_week': {
      from = startOfDay(now); from.setDate(from.getDate() - from.getDay());
      break;
    }
    case 'this_month':
      from = new Date(now.getFullYear(), now.getMonth(), 1);
      break;
    case '3_months':
      from = new Date(now.getFullYear(), now.getMonth() - 3, now.getDate());
      break;
    case '6_months':
      from = new Date(now.getFullYear(), now.getMonth() - 6, now.getDate());
      break;
    case '1_year':
      from = new Date(now.getFullYear() - 1, now.getMonth(), now.getDate());
      break;
    case '2_years':
      from = new Date(now.getFullYear() - 2, now.getMonth(), now.getDate());
      break;
    case 'custom':
      from = fromParam ? new Date(fromParam) : startOfDay(now);
      to = toParam ? new Date(new Date(toParam).getTime() + 86400000) : to;
      break;
    default:
      from = startOfDay(now);
  }
  return { from: from.toISOString(), to: to.toISOString() };
}

// ============================= DOCTOR ANALYTICS =============================
async function getDoctorAnalytics(doctorId, range, fromParam, toParam) {
  const { from, to } = resolveDateRange(range, fromParam, toParam);

  const patientsQ = pool.query(
    `SELECT COUNT(*)::int AS c FROM visits WHERE doctor_id = $1 AND created_at >= $2 AND created_at < $3 AND status != 'waiting'`,
    [doctorId, from, to]
  );
  const consultingFeeQ = pool.query(
    `SELECT COALESCE(SUM(b.consulting_fee),0)::numeric(10,2) AS s FROM bills b
     JOIN visits v ON v.id = b.visit_id
     WHERE v.doctor_id = $1 AND b.created_at >= $2 AND b.created_at < $3`,
    [doctorId, from, to]
  );
  const medicineRevenueQ = pool.query(
    `SELECT COALESCE(SUM(bi.line_total),0)::numeric(10,2) AS s FROM bill_items bi
     JOIN bills b ON b.id = bi.bill_id
     JOIN visits v ON v.id = b.visit_id
     WHERE v.doctor_id = $1 AND b.created_at >= $2 AND b.created_at < $3`,
    [doctorId, from, to]
  );
  const medicinesSoldQ = pool.query(
    `SELECT COUNT(*)::int AS c FROM bill_items bi
     JOIN bills b ON b.id = bi.bill_id
     JOIN visits v ON v.id = b.visit_id
     WHERE v.doctor_id = $1 AND b.created_at >= $2 AND b.created_at < $3`,
    [doctorId, from, to]
  );
  const dailyQ = pool.query(
    `SELECT b.created_at::date AS day,
       COALESCE(SUM(bi.line_total),0)::numeric(10,2) AS medicine_revenue,
       COALESCE(MAX(b.consulting_fee),0)::numeric(10,2) AS fee_sample
     FROM bills b
     JOIN visits v ON v.id = b.visit_id
     LEFT JOIN bill_items bi ON bi.bill_id = b.id
     WHERE v.doctor_id = $1 AND b.created_at >= $2 AND b.created_at < $3
     GROUP BY b.created_at::date ORDER BY day`,
    [doctorId, from, to]
  );
  const dailyPatientsQ = pool.query(
    `SELECT created_at::date AS day, COUNT(*)::int AS c FROM visits
     WHERE doctor_id = $1 AND created_at >= $2 AND created_at < $3 AND status != 'waiting'
     GROUP BY created_at::date ORDER BY day`,
    [doctorId, from, to]
  );

  const topMedicinesQ = pool.query(
    `SELECT bi.medicine_name, COUNT(*)::int AS times_sold, COALESCE(SUM(bi.line_total),0)::numeric(10,2) AS revenue
     FROM bill_items bi
     JOIN bills b ON b.id = bi.bill_id
     JOIN visits v ON v.id = b.visit_id
     WHERE v.doctor_id = $1 AND b.created_at >= $2 AND b.created_at < $3
     GROUP BY bi.medicine_name ORDER BY revenue DESC LIMIT 8`,
    [doctorId, from, to]
  );

  const [patients, consultingFee, medicineRevenue, medicinesSold, daily, dailyPatients, topMedicines] = await Promise.all([
    patientsQ, consultingFeeQ, medicineRevenueQ, medicinesSoldQ, dailyQ, dailyPatientsQ, topMedicinesQ,
  ]);

  return {
    range: { from, to },
    patientCount: patients.rows[0].c,
    totalConsultingFee: consultingFee.rows[0].s,
    totalMedicineRevenue: medicineRevenue.rows[0].s,
    medicinesSold: medicinesSold.rows[0].c,
    totalRevenue: Number(consultingFee.rows[0].s) + Number(medicineRevenue.rows[0].s),
    dailyRevenue: daily.rows,
    dailyPatients: dailyPatients.rows,
    topMedicines: topMedicines.rows,
  };
}

// ============================= HISTORY (completed visits, kept forever) =============================
async function getDoctorHistory(doctorId, range, fromParam, toParam) {
  const { from, to } = resolveDateRange(range, fromParam, toParam);
  const { rows } = await pool.query(
    `SELECT v.*, p.first_name, p.last_name, p.phone
     FROM visits v JOIN patients p ON p.id = v.patient_id
     WHERE v.doctor_id = $1 AND v.status != 'waiting' AND v.created_at >= $2 AND v.created_at < $3
     ORDER BY v.created_at DESC`,
    [doctorId, from, to]
  );
  return rows;
}

async function getBillingHistory(range, fromParam, toParam) {
  const { from, to } = resolveDateRange(range, fromParam, toParam);
  const { rows } = await pool.query(
    `SELECT b.*, (SELECT COUNT(*)::int FROM bill_items WHERE bill_id = b.id) AS item_count
     FROM bills b WHERE b.created_at >= $1 AND b.created_at < $2 ORDER BY b.created_at DESC`,
    [from, to]
  );
  return rows;
}

