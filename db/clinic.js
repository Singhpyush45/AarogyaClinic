// db/clinic.js
// -----------------------------------------------------------------------
// Clinic Workflow System (Phase 1): staff roles, patient intake, doctor
// queue, digital prescriptions, medicine master, and billing.
// All tables are ADDITIVE — existing appointments/reviews are untouched.
// -----------------------------------------------------------------------
const bcrypt = require('bcryptjs');
const { pool } = require('./database');

// ============================= SCHEMA =============================
async function initClinicDb() {
  // Persistent binary storage for images (doctor photo, staff photos) —
  // stored IN the database so they survive Render/Railway redeploys,
  // instead of the local filesystem which resets on free tiers.
  await pool.query(`
    CREATE TABLE IF NOT EXISTS clinic_assets (
      key         TEXT PRIMARY KEY,
      data        BYTEA NOT NULL,
      mime_type   TEXT NOT NULL,
      updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
    );
  `);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS staff_users (
      id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      username       TEXT UNIQUE NOT NULL,
      password_hash  TEXT NOT NULL,
      role           TEXT NOT NULL CHECK (role IN ('doctor','reception','billing')),
      active         BOOLEAN NOT NULL DEFAULT true,
      created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
    );
  `);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS staff_profiles (
      staff_user_id        BIGINT PRIMARY KEY REFERENCES staff_users(id) ON DELETE CASCADE,
      full_name            TEXT,
      age                  INTEGER,
      mobile               TEXT,
      address              TEXT,
      registration_number  TEXT,
      photo_data           BYTEA,
      photo_mime           TEXT,
      updated_at           TIMESTAMPTZ NOT NULL DEFAULT now()
    );
  `);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS patients (
      id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      first_name  TEXT NOT NULL,
      last_name   TEXT,
      phone       TEXT NOT NULL,
      gender      TEXT,
      dob         TEXT,
      age         INTEGER,
      address     TEXT,
      created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
    );
  `);
  await pool.query(`CREATE INDEX IF NOT EXISTS idx_patients_phone ON patients(phone);`);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS visits (
      id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      patient_id        BIGINT NOT NULL REFERENCES patients(id),
      bp                TEXT,
      temperature       TEXT,
      pulse             TEXT,
      weight            TEXT,
      chief_complaint   TEXT,
      notes             TEXT,
      status            TEXT NOT NULL DEFAULT 'waiting',
      created_by        BIGINT REFERENCES staff_users(id),
      doctor_id         BIGINT REFERENCES staff_users(id),
      created_at        TIMESTAMPTZ NOT NULL DEFAULT now()
    );
  `);
  await pool.query(`CREATE INDEX IF NOT EXISTS idx_visits_status ON visits(status);`);
  await pool.query(`CREATE INDEX IF NOT EXISTS idx_visits_patient ON visits(patient_id);`);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS medicines (
      id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name        TEXT NOT NULL,
      strength    TEXT,
      price       NUMERIC(10,2),
      category    TEXT,
      active      BOOLEAN NOT NULL DEFAULT true,
      created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
    );
  `);
  await pool.query(`CREATE INDEX IF NOT EXISTS idx_medicines_name ON medicines(name);`);

  // additive migration: inventory fields for existing medicines table
  await pool.query(`ALTER TABLE medicines ADD COLUMN IF NOT EXISTS stock_quantity INTEGER;`);
  await pool.query(`ALTER TABLE medicines ADD COLUMN IF NOT EXISTS low_stock_threshold INTEGER NOT NULL DEFAULT 10;`);
  await pool.query(`ALTER TABLE medicines ADD COLUMN IF NOT EXISTS expiry_date DATE;`);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS prescriptions (
      id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      visit_id                 BIGINT NOT NULL REFERENCES visits(id),
      doctor_id                BIGINT REFERENCES staff_users(id),
      mode                     TEXT NOT NULL DEFAULT 'digital',
      chief_complaint          TEXT,
      examination              TEXT,
      diagnosis                TEXT,
      procedure_notes          TEXT,
      advice                   TEXT,
      investigation            TEXT,
      prognosis                TEXT,
      findings                 TEXT,
      doctor_notes             TEXT,
      emergency_instructions   TEXT,
      follow_up                TEXT,
      created_at               TIMESTAMPTZ NOT NULL DEFAULT now()
    );
  `);
  await pool.query(`CREATE INDEX IF NOT EXISTS idx_prescriptions_visit ON prescriptions(visit_id);`);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS prescription_medicines (
      id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      prescription_id   BIGINT NOT NULL REFERENCES prescriptions(id) ON DELETE CASCADE,
      medicine_id       BIGINT REFERENCES medicines(id),
      medicine_name     TEXT NOT NULL,
      dosage            TEXT,
      instructions      TEXT,
      quantity          INTEGER NOT NULL DEFAULT 1,
      price             NUMERIC(10,2)
    );
  `);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS quick_type_suggestions (
      id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      section      TEXT NOT NULL,
      text         TEXT NOT NULL,
      created_by   BIGINT REFERENCES staff_users(id),
      created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
    );
  `);
  await pool.query(`CREATE INDEX IF NOT EXISTS idx_quicktype_section ON quick_type_suggestions(section);`);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS bills (
      id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      visit_id       BIGINT NOT NULL REFERENCES visits(id),
      bill_number    TEXT UNIQUE NOT NULL,
      patient_name   TEXT NOT NULL,
      patient_phone  TEXT NOT NULL,
      doctor_name    TEXT,
      subtotal       NUMERIC(10,2) NOT NULL DEFAULT 0,
      discount       NUMERIC(10,2) NOT NULL DEFAULT 0,
      grand_total    NUMERIC(10,2) NOT NULL DEFAULT 0,
      created_by     BIGINT REFERENCES staff_users(id),
      created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
    );
  `);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS bill_items (
      id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      bill_id        BIGINT NOT NULL REFERENCES bills(id) ON DELETE CASCADE,
      medicine_name  TEXT NOT NULL,
      quantity       INTEGER NOT NULL DEFAULT 1,
      unit_price     NUMERIC(10,2) NOT NULL DEFAULT 0,
      line_total     NUMERIC(10,2) NOT NULL DEFAULT 0
    );
  `);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS prescription_photos (
      id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      visit_id     BIGINT NOT NULL REFERENCES visits(id),
      data         BYTEA NOT NULL,
      mime_type    TEXT NOT NULL,
      uploaded_by  BIGINT REFERENCES staff_users(id),
      uploaded_at  TIMESTAMPTZ NOT NULL DEFAULT now()
    );
  `);
  await pool.query(`CREATE INDEX IF NOT EXISTS idx_prescription_photos_visit ON prescription_photos(visit_id);`);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS visit_attachments (
      id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      visit_id     BIGINT NOT NULL REFERENCES visits(id),
      filename     TEXT NOT NULL,
      data         BYTEA NOT NULL,
      mime_type    TEXT NOT NULL,
      uploaded_by  BIGINT REFERENCES staff_users(id),
      uploaded_at  TIMESTAMPTZ NOT NULL DEFAULT now()
    );
  `);
  await pool.query(`CREATE INDEX IF NOT EXISTS idx_attachments_visit ON visit_attachments(visit_id);`);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS audit_log (
      id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      staff_id    BIGINT REFERENCES staff_users(id),
      role        TEXT,
      action      TEXT NOT NULL,
      details     TEXT,
      created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
    );
  `);
  await pool.query(`CREATE INDEX IF NOT EXISTS idx_audit_created ON audit_log(created_at DESC);`);

  // ---- clinic_settings: simple key/value store (consulting fee, etc.) ----
  await pool.query(`
    CREATE TABLE IF NOT EXISTS clinic_settings (
      key         TEXT PRIMARY KEY,
      value       TEXT,
      updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
    );
  `);
  await pool.query(`
    INSERT INTO clinic_settings (key, value) VALUES ('consulting_fee', '0')
    ON CONFLICT (key) DO NOTHING;
  `);

  // additive: bill_items needs medicine_id so stock can be auto-deducted on billing
  await pool.query(`ALTER TABLE bill_items ADD COLUMN IF NOT EXISTS medicine_id BIGINT REFERENCES medicines(id);`);

  // additive: bills need a consulting fee line + a "history retained" status marker
  await pool.query(`ALTER TABLE bills ADD COLUMN IF NOT EXISTS consulting_fee NUMERIC(10,2) NOT NULL DEFAULT 0;`);

  // one-time data fix: correct the doctor's name if it was seeded/saved before the spelling fix
  await pool.query(`
    UPDATE staff_profiles SET full_name = 'Dr. Alok Kushwaha', updated_at = now()
    WHERE full_name = 'Dr. Aalok Kushwaha';
  `);

  // allow deleting a staff account without blocking on history —
  // historical visits/bills/etc. stay intact, just with no staff link
  const staffFkFixes = [
    ['visits', 'created_by'],
    ['visits', 'doctor_id'],
    ['prescriptions', 'doctor_id'],
    ['quick_type_suggestions', 'created_by'],
    ['bills', 'created_by'],
    ['visit_attachments', 'uploaded_by'],
    ['prescription_photos', 'uploaded_by'],
    ['audit_log', 'staff_id'],
  ];
  for (const [table, column] of staffFkFixes) {
    const constraintName = `${table}_${column}_fkey`;
    await pool.query(`ALTER TABLE ${table} DROP CONSTRAINT IF EXISTS ${constraintName};`);
    await pool.query(
      `ALTER TABLE ${table} ADD CONSTRAINT ${constraintName}
       FOREIGN KEY (${column}) REFERENCES staff_users(id) ON DELETE SET NULL;`
    );
  }

  await seedDefaults();
  console.log('  ✓ Clinic workflow schema ready (staff, patients, visits, prescriptions, medicines, bills)');
}

// Seed a default account per role + a few starter Quick Type suggestions,
// ONLY if none exist yet — never overwrites real data.
async function seedDefaults() {
  const { rows } = await pool.query(`SELECT COUNT(*)::int AS c FROM staff_users`);
  if (rows[0].c === 0) {
    const defaults = [
      { username: 'doctor', password: 'doctor123', role: 'doctor', name: 'Dr. Alok Kushwaha' },
      { username: 'reception', password: 'reception123', role: 'reception', name: 'Reception Staff' },
      { username: 'billing', password: 'billing123', role: 'billing', name: 'Billing Staff' },
    ];
    for (const d of defaults) {
      const hash = bcrypt.hashSync(d.password, 10);
      const { rows: userRows } = await pool.query(
        `INSERT INTO staff_users (username, password_hash, role) VALUES ($1, $2, $3) RETURNING id`,
        [d.username, hash, d.role]
      );
      await pool.query(
        `INSERT INTO staff_profiles (staff_user_id, full_name) VALUES ($1, $2)`,
        [userRows[0].id, d.name]
      );
    }
    console.log('  ✓ Seeded default staff accounts (doctor/doctor123, reception/reception123, billing/billing123) — CHANGE THESE PASSWORDS');
  }

  const { rows: qtRows } = await pool.query(`SELECT COUNT(*)::int AS c FROM quick_type_suggestions`);
  if (qtRows[0].c === 0) {
    const defaultSuggestions = {
      chief_complaint: ['Fever', 'Headache', 'Cold & Cough', 'Body ache', 'Stomach ache', 'Joint pain'],
      examination: ['Normal', 'Mild tenderness', 'No abnormality detected', 'Throat congested'],
      diagnosis: ['Viral fever', 'Acute gastritis', 'Allergic rhinitis', 'Migraine'],
      advice: ['Plenty of fluids', 'Rest for 2-3 days', 'Light diet', 'Avoid cold food/drinks'],
      investigation: ['CBC', 'Blood sugar (fasting)', 'Urine routine', 'Not required'],
      follow_up: ['After 3 days', 'After 1 week', 'SOS (if needed)', 'After 2 weeks'],
    };
    for (const [section, items] of Object.entries(defaultSuggestions)) {
      for (const text of items) {
        await pool.query(
          `INSERT INTO quick_type_suggestions (section, text) VALUES ($1, $2)`,
          [section, text]
        );
      }
    }
  }
}

// ============================= STAFF =============================
async function getStaffByUsername(username, role) {
  const { rows } = await pool.query(
    `SELECT su.*, sp.full_name, sp.age, sp.mobile, sp.address, sp.registration_number, sp.updated_at AS profile_updated_at
     FROM staff_users su LEFT JOIN staff_profiles sp ON sp.staff_user_id = su.id
     WHERE su.username = $1 AND su.role = $2 AND su.active = true`,
    [username, role]
  );
  return rows[0] || null;
}

async function getStaffById(id) {
  const { rows } = await pool.query(
    `SELECT su.*, sp.full_name, sp.age, sp.mobile, sp.address, sp.registration_number
     FROM staff_users su LEFT JOIN staff_profiles sp ON sp.staff_user_id = su.id
     WHERE su.id = $1`,
    [id]
  );
  return rows[0] || null;
}

async function listStaff() {
  const { rows } = await pool.query(
    `SELECT su.id, su.username, su.role, su.active, su.created_at, sp.full_name, sp.mobile
     FROM staff_users su LEFT JOIN staff_profiles sp ON sp.staff_user_id = su.id
     ORDER BY su.role, su.username`
  );
  return rows;
}

async function createStaff({ username, password, role }) {
  const hash = bcrypt.hashSync(password, 10);
  const { rows } = await pool.query(
    `INSERT INTO staff_users (username, password_hash, role) VALUES ($1, $2, $3) RETURNING id, username, role, active, created_at`,
    [username, hash, role]
  );
  await pool.query(`INSERT INTO staff_profiles (staff_user_id) VALUES ($1)`, [rows[0].id]);
  return rows[0];
}

